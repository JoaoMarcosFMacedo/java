

public class Endereco{
    
    String nomeLogradouro;
    int numeroRua;
    String bairro;
    String city;
    String estado;

    Endereco(String nomeLogradouro, int numeroRua, String bairro, String city, String estado){

        this.nomeLogradouro = nomeLogradouro;
        this.numeroRua = numeroRua;
        this.bairro = bairro;
        this.city = city;
        this.estado = estado;
        
    }
}
